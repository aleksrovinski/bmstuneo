// Regenerates lib/services/bmstu_groups_bundled.dart from the public LKS structure.
//
// The bundled list is only the offline fallback: the app downloads a fresh catalog
// itself. Re-run before a release so first launch without network is up to date:
//
//   dart run tool/update_groups_catalog.dart
import 'dart:convert';
import 'dart:io';

const _structureUrl = 'https://lks.bmstu.ru/lks-back/api/v1/structure';
const _outputPath = 'lib/services/bmstu_groups_bundled.dart';

Future<void> main() async {
  final client = HttpClient();
  try {
    final request = await client.getUrl(Uri.parse(_structureUrl));
    request.headers.set(HttpHeaders.acceptHeader, 'application/json');
    final response = await request.close();
    if (response.statusCode != 200) {
      stderr.writeln('GET $_structureUrl -> ${response.statusCode}');
      exitCode = 1;
      return;
    }
    final json = jsonDecode(await response.transform(utf8.decoder).join()) as Map<String, dynamic>;

    final groups = <String, String>{};
    void walk(Map<String, dynamic> node) {
      final uuid = node['uuid']?.toString();
      final title = node['abbr']?.toString();
      if (node['nodeType'] == 'group' && uuid != null && title != null && title.isNotEmpty) {
        groups[title] = uuid;
      }
      for (final child in (node['children'] as List? ?? const []).whereType<Map<String, dynamic>>()) {
        walk(child);
      }
    }

    walk(json['data'] as Map<String, dynamic>);
    if (groups.isEmpty) {
      stderr.writeln('No groups found in the structure response');
      exitCode = 1;
      return;
    }

    final titles = groups.keys.toList()..sort();
    final out = StringBuffer()
      ..writeln('// GENERATED by tool/update_groups_catalog.dart — do not edit by hand.')
      ..writeln('// Source: $_structureUrl (${json['date'] ?? 'unknown date'}), ${titles.length} groups.')
      ..writeln()
      ..writeln('const Map<String, String> bundledGroups = {');
    for (final title in titles) {
      out.writeln("  '${title.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}': '${groups[title]}',");
    }
    out.writeln('};');

    File(_outputPath).writeAsStringSync(out.toString());
    stdout.writeln('Wrote ${titles.length} groups to $_outputPath');
  } finally {
    client.close();
  }
}
